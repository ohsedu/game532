--
--  왜 옮겼나.
--
--  이 앱과 talk532(웹톡532)가 Supabase 프로젝트 **하나**를 공유합니다. 게임에서
--  로그인한 사람이 곧 그 앱의 사용자여야 하고, 랭킹의 '대화하기' 가 그 앱의 1:1
--  방으로 이어져야 하는데, 그 둘은 auth.users 와 profiles 를 같이 볼 수 있어야만
--  성립합니다.
--
--  그 DB 에 무엇을 어떤 순서로 올리는지는 talk532 의
--  scripts/build-run-sql.mjs 의 ORDER 하나가 정합니다. 서른 개 가까운 SQL 파일이
--  서로의 함수를 다시 정의하며 쌓이고, 순서를 어기면 에러가 나는 게 아니라
--  **조용히 옛 정의로 되돌아갑니다.** 점수 테이블만 이 저장소에 따로 두면 그
--  순서 밖에 놓이고, 두 곳 중 한쪽이 언젠가 뒤처집니다.
--
--  이 파일을 지우지 않고 남겨 둔 것은, 여기 있던 것을 찾으러 오는 사람에게
--  어디로 갔는지 알려 줄 자리가 필요해서입니다.
--
--
--  이 앱은 한때 자기 Supabase 프로젝트를 따로 썼습니다. 거기 쌓인 점수 스무 줄은
--  통합 프로젝트로 옮긴 뒤 옛 프로젝트를 지웠으므로, 이제 남은 곳은 한 군데입니다.
--
--  옮겨온 줄은 전부 `user_id` 가 비어 있습니다 — 그 시절에는 로그인이 없어서
--  남은 것이 사람이 적어 넣은 닉네임뿐이었고, 그것으로 계정을 짚으면 남의 이름을
--  적었던 사람의 점수가 그 사람 계정에 붙습니다. 그래서 랭킹에는 같은 이름이
--  여러 줄 보일 수 있습니다(비회원 줄은 접지 않습니다). 그 사람이 로그인해서 한 판
--  하면 그때부터 쌓이는 회원 줄은 사람당 하나로 접힙니다.
