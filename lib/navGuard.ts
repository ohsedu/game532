"use client";

/**
 * "지금 나가면 잃는 것이 있다" 를 헤더에 알려 두는 자리.
 *
 * 메시지함은 헤더에 있고 게임은 그 아래 판에 있다. 한 판 하는 중에 메시지를
 * 눌러 talk532 로 건너가면 그 판은 그대로 사라지는데, 헤더 쪽 컴포넌트는
 * 게임이 도는지를 알 방법이 없다 — 둘은 형제도 아니고 부모-자식도 아니다.
 *
 * props 로 꿰지 않고 모듈 전역에 두는 이유는 그 실이 지나갈 길이 없어서다.
 * 헤더는 홈에도 있고 게임 화면에도 있는데, 홈에는 게임이 없으므로 그쪽은
 * 아무것도 걸지 않고 지나간다(걸린 것이 없으면 곧장 이동).
 *
 * talk532/lib/roomOpener.ts 와 같은 모양이다.
 */

/** 걸려 있으면 "물어봐야 하는 상태" 다. 문구를 돌려준다. */
let guard: (() => string | null) | null = null;

/**
 * 게임 화면이 한 판 도는 동안 걸어 두고, 끝나면 null 로 되돌린다.
 *
 * 되돌리는 것을 잊으면 게임을 끝낸 뒤에도 메시지를 누를 때마다 확인창이 뜬다 —
 * 거는 쪽에서 useEffect 의 정리 함수로 반드시 풀 것.
 */
export function setNavGuard(fn: (() => string | null) | null) {
  guard = fn;
}

/**
 * 지금 떠나도 되는가. 물어볼 것이 있으면 그 문구, 없으면 null.
 *
 * 걸어 둔 쪽이 사라진 뒤에 호출될 수도 있으므로 예외는 여기서 삼킨다 —
 * 확인창을 못 띄우는 것이 이동 자체를 막는 것보다 낫다.
 */
export function askNavGuard(): string | null {
  try {
    return guard?.() ?? null;
  } catch {
    return null;
  }
}
